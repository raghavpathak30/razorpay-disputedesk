"""Measures how well the LLM's `customer_communication_log` normalisation
(SPEC.md §2) recovers `true_fraud`, against the TF-IDF + logistic regression
baseline recorded in DECISIONS.md's 2026-08-31 "Generator calibration" entry
(AUC 0.6371, 5-fold CV) - the bar this project's own notes name as what the
LLM path should measurably beat.

Feature extraction, evaluation methodology (logistic regression, 5-fold
stratified CV, ROC AUC), and the fixed `random_state` below are frozen
before this module is ever run against a real LLM. Do not edit this file,
the normalisation prompt, or `random_state` after seeing a result to chase a
better number - report whatever comes out.

This module makes real network calls through whatever `LLMClient` it is
given. The pure post-processing (`normalized_to_feature_vector`,
`auc_of_normalized_fields`) is unit-tested with synthetic data; the
network-touching `run_llm_normalization_sample` is tested only with
`FakeLLMClient` (CLAUDE.md: no test may make a network call) - the real
measurement against the live API is a one-off script run, recorded in
DECISIONS.md, not a repeatable automated test.
"""

import time

import httpx
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold

from disputedesk.evidence.llm import LLMClient
from disputedesk.evidence.normalize_comms import NormalizationResult, normalize_communication_log
from disputedesk.evidence.schemas import NormalizedCommunicationLog
from disputedesk.generator.config import GeneratorConfig
from disputedesk.generator.pipeline import generate_dataset

# Recorded in DECISIONS.md, 2026-08-31 "Generator calibration": TF-IDF +
# logistic regression on the same `customer_communication_log` ->
# `true_fraud` task, 5-fold CV. The baseline this measurement compares
# against - never recomputed here, only cited.
TFIDF_BASELINE_AUC: float = 0.6371

FEATURE_COLUMNS: tuple[str, ...] = (
    "claims_unauthorized_transaction",
    "mentions_prior_bank_contact",
    "mentions_shared_card_access",
    "mentions_travel",
    "is_substantive",
    "tone_polite",
    "tone_terse",
)


def normalized_to_feature_vector(normalized: NormalizedCommunicationLog) -> dict:
    """The LLM's typed output fields, encoded numerically for a downstream
    classifier - never the free-text `summary`, since the comparison is
    specifically about the *typed fields* SPEC.md §2 asks the LLM to
    produce. `tone` is one-hot encoded with `"neutral"` as the implicit
    baseline (both `tone_polite` and `tone_terse` are 0).
    """
    return {
        "claims_unauthorized_transaction": int(normalized.claims_unauthorized_transaction),
        "mentions_prior_bank_contact": int(normalized.mentions_prior_bank_contact),
        "mentions_shared_card_access": int(normalized.mentions_shared_card_access),
        "mentions_travel": int(normalized.mentions_travel),
        "is_substantive": int(normalized.is_substantive),
        "tone_polite": int(normalized.tone == "polite"),
        "tone_terse": int(normalized.tone == "terse"),
    }


def auc_of_normalized_fields(
    feature_rows: list[dict],
    true_fraud: list[bool] | np.ndarray,
    n_splits: int = 5,
    random_state: int = 0,
) -> dict:
    """5-fold stratified CV, logistic regression, ROC AUC per fold - the
    same downstream-classifier methodology the TF-IDF baseline used, so the
    comparison isolates the feature-extraction step (LLM normalisation vs.
    TF-IDF), not the classifier.
    """
    X = pd.DataFrame(feature_rows, columns=list(FEATURE_COLUMNS)).to_numpy(dtype=float)
    y = np.asarray(true_fraud, dtype=int)

    cv = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=random_state)
    fold_aucs = []
    for train_idx, test_idx in cv.split(X, y):
        model = LogisticRegression(max_iter=1000, random_state=random_state)
        model.fit(X[train_idx], y[train_idx])
        predicted_p = model.predict_proba(X[test_idx])[:, 1]
        fold_aucs.append(float(roc_auc_score(y[test_idx], predicted_p)))

    return {
        "fold_aucs": fold_aucs,
        "mean_auc": float(np.mean(fold_aucs)),
        "std_auc": float(np.std(fold_aucs)),
        "n": len(y),
        "prevalence": float(y.mean()),
    }


def _normalize_with_429_retry(
    raw_log: str,
    llm_client: LLMClient,
    max_retries: int,
    retry_sleep_seconds: float,
) -> NormalizationResult:
    """`normalize_communication_log`, retrying only on HTTP 429 (rate
    limited) - a transient infrastructure condition, not an LLM output
    quality issue, so retrying here touches neither the prompt nor the
    measurement's methodology. Any other error propagates immediately.
    """
    for attempt in range(max_retries + 1):
        try:
            return normalize_communication_log(raw_log, llm_client)
        except httpx.HTTPStatusError as error:
            if error.response.status_code != 429 or attempt == max_retries:
                raise
            wait_seconds = float(error.response.headers.get("retry-after", retry_sleep_seconds))
            time.sleep(wait_seconds)
    raise AssertionError("unreachable: loop always returns or raises")


def run_llm_normalization_sample(
    n_rows: int,
    seed: int,
    generator_config: GeneratorConfig,
    llm_client: LLMClient,
    sleep_seconds: float = 0.0,
    max_429_retries: int = 3,
    retry_sleep_seconds: float = 20.0,
) -> pd.DataFrame:
    """Generate `n_rows` synthetic disputes and normalise each
    `customer_communication_log` via `llm_client`. `true_fraud` is a debug-
    only generator field (eval-use only, same convention as `eval.oracle`'s
    use of the debug `p` column - never a model or policy input).
    `sleep_seconds` paces real API calls to respect rate limits; leave at 0
    (default) for `FakeLLMClient`, which needs no pacing and never raises
    `httpx.HTTPStatusError`, so the retry path is inert in tests.
    """
    features_df, debug_df = generate_dataset(n_rows, seed, generator_config)

    rows = []
    for position, idx in enumerate(features_df.index):
        if position > 0 and sleep_seconds > 0:
            time.sleep(sleep_seconds)
        raw_log = features_df.loc[idx, "customer_communication_log"]
        result = _normalize_with_429_retry(
            raw_log, llm_client, max_429_retries, retry_sleep_seconds
        )
        rows.append(
            {
                "true_fraud": bool(debug_df.loc[idx, "true_fraud"]),
                "human_review_required": result.human_review_required,
                **normalized_to_feature_vector(result.normalized),
            }
        )
    return pd.DataFrame(rows)
